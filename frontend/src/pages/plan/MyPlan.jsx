import { useEffect, useState } from "react";
import { Link } from "react-router-dom";

import {
  FiTarget,
  FiTrendingUp,
  FiCalendar,
  FiZap,
  FiArrowRight,
  FiCheckCircle,
  FiCircle,
  FiClock,
  FiAlertCircle,
  FiBookOpen,
  FiMap,
  FiSliders,
  FiRefreshCw,
  FiInfo,
  FiLoader,
  FiPlay
} from "react-icons/fi";

import { getToken, toApiError } from "../../services/api";
import { getMyPlan, setPlanTaskCompleted } from "../../services/planService";
import { getTrack } from "../career/careerTrackData";

/* =====================================================
   MY PLAN — GET /api/plan/me
   Generated by the backend from the user's target role, skill gap,
   recent practice and preferences. Only completion is stored.
===================================================== */

const TYPE_LABELS = {
  TECHNICAL: "Technical Practice",
  CODING: "Coding",
  SQL: "SQL",
  APTITUDE: "Aptitude",
  SYSTEM_DESIGN: "System Design",
  VOICE: "Voice Practice",
  DAILY_CHALLENGE: "Daily Challenge",
  INTERVIEW: "Interview",
  STUDY: "Study"
};

const PRIORITY_LABELS = { HIGH: "High priority", MEDIUM: "Medium", LOW: "Low" };


function MyPlan() {
  const signedIn = Boolean(getToken());

  const [plan, setPlan] = useState(null);
  const [loading, setLoading] = useState(signedIn);
  const [error, setError] = useState("");
  const [reloadKey, setReloadKey] = useState(0);
  const [savingKey, setSavingKey] = useState(null);
  const [taskError, setTaskError] = useState("");

  useEffect(() => {
    if (!signedIn) return undefined;

    let cancelled = false;

    getMyPlan()
      .then((data) => {
        if (!cancelled) {
          setPlan(data);
          setError("");
        }
      })
      .catch((err) => {
        if (cancelled) return;
        const { status, message } = toApiError(err);
        setError(status === 0 ? "Unable to connect to CareerAI server." : message);
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });

    return () => {
      cancelled = true;
    };
  }, [signedIn, reloadKey]);

  const retry = () => {
    setLoading(true);
    setError("");
    setReloadKey((key) => key + 1);
  };

  const toggleTask = async (task) => {
    if (savingKey || task.completionSource === "PRACTICE") return;

    setSavingKey(task.id);
    setTaskError("");

    try {
      // PUT /api/plan/tasks/{id}/complete|incomplete returns the updated plan.
      setPlan(await setPlanTaskCompleted(task.id, !task.completed));
    } catch (err) {
      const { status, message } = toApiError(err);
      setTaskError(status === 0 ? "Unable to connect to CareerAI server." : message);
    } finally {
      setSavingKey(null);
    }
  };

  return (
    <div className="ua-page">

      <header className="ua-page-header">

        <div>
          <span className="ua-eyebrow">MY PREPARATION PLAN</span>
          <h1>{plan ? `Your plan for ${plan.targetRole}` : "Your preparation plan"}</h1>
          <p>
            Today's tasks are generated from your skill gap, recent practice
            and preparation preferences.
          </p>
        </div>

        <div className="ua-header-actions">
          <Link
            to="/career-tracks"
            className="ua-button ghost"
          >
            <FiRefreshCw aria-hidden="true" />
            Change target role
          </Link>
          <Link
            to="/profile"
            className="ua-button ghost"
          >
            <FiSliders aria-hidden="true" />
            Daily time
          </Link>
        </div>

      </header>

      {!signedIn ? (
        <PlanStatus
          icon={<FiInfo />}
          message="Create a free account to get a personalized plan built from your target role and practice results."
          action={<Link to="/register" className="ua-button primary">Create account</Link>}
        />
      ) : loading ? (
        <PlanStatus icon={<FiLoader className="auth-spinner" />} message="Building today's plan…" role="status" />
      ) : error ? (
        <PlanStatus
          icon={<FiAlertCircle />}
          message={error}
          role="alert"
          action={(
            <button type="button" className="ua-button primary" onClick={retry}>
              <FiRefreshCw aria-hidden="true" />
              Try again
            </button>
          )}
        />
      ) : (
        <PlanContent
          plan={plan}
          savingKey={savingKey}
          taskError={taskError}
          onToggle={toggleTask}
        />
      )}

    </div>
  );
}


function PlanStatus({ icon, message, action, role }) {
  return (
    <section className="ua-card">
      <div className="ua-empty" role={role}>
        <span aria-hidden="true">{icon}</span>
        <p>{message}</p>
        {action}
      </div>
    </section>
  );
}


function PlanContent({ plan, savingKey, taskError, onToggle }) {
  const progress = plan.totalTasks ? Math.round((plan.completedTasks / plan.totalTasks) * 100) : 0;
  const track = getTrack(plan.trackId);
  const next = plan.recommendedNextAction;

  return (
    <>

      {!plan.targetRoleSelected && (
        <div className="ua-demo-banner">
          <FiInfo aria-hidden="true" />
          <p>
            <strong>No target role set.</strong> This plan uses {plan.targetRole} as an example.{" "}
            <Link to="/profile">Choose your target role</Link> to personalise it.
          </p>
        </div>
      )}


      {/* SUMMARY */}

      <section className="ua-stat-grid">

        <Link
          to={`/career-tracks/${plan.trackId}`}
          className="ua-stat ua-stat-link"
        >
          <span className="ua-stat-icon" aria-hidden="true"><FiTarget /></span>
          <span className="ua-stat-label">Target Role</span>
          <strong className="ua-stat-value small">{plan.targetRole}</strong>
          <small>View roadmap →</small>
        </Link>

        <Link
          to="/career/skill-gap"
          className="ua-stat ua-stat-link"
        >
          <span className="ua-stat-icon" aria-hidden="true"><FiTrendingUp /></span>
          <span className="ua-stat-label">Readiness</span>
          <strong className="ua-stat-value">{plan.readiness != null ? `${plan.readiness}%` : "—"}</strong>
          <small>Assessed {plan.assessedSkillCount} of {plan.totalRequiredSkillCount} skills</small>
        </Link>

        <div className="ua-stat">
          <span className="ua-stat-icon" aria-hidden="true"><FiCalendar /></span>
          <span className="ua-stat-label">Daily Goal</span>
          <strong className="ua-stat-value">{plan.dailyPreparationMinutes} min</strong>
          <small>{plan.plannedMinutes} min planned today · {plan.preferredDifficulty}</small>
        </div>

        <div className="ua-stat">
          <span className="ua-stat-icon" aria-hidden="true"><FiZap /></span>
          <span className="ua-stat-label">Practice Streak</span>
          <strong className="ua-stat-value">{plan.currentStreak} {plan.currentStreak === 1 ? "day" : "days"}</strong>
          <small>Days in a row with saved practice</small>
        </div>

      </section>


      <div className="plan-main-grid">

        {/* TODAY'S TASKS */}

        <section className="ua-card plan-today">

          <div className="ua-card-header">
            <div>
              <span className="ua-card-kicker">TODAY'S TASKS</span>
              <h2>
                {new Date(`${plan.date}T00:00:00`).toLocaleDateString(undefined, { weekday: "long", day: "numeric", month: "long" })}
              </h2>
            </div>
            <span className="ua-chip">
              <FiClock aria-hidden="true" />
              {plan.plannedMinutes} min
            </span>
          </div>

          {plan.tasks.length === 0 ? (
            <div className="ua-empty">
              <p>No tasks for today. Check your Skill Gap or browse practice modules.</p>
              <Link to="/practice" className="ua-button primary small">Browse practice</Link>
            </div>
          ) : (
            <>
              <div className="plan-progress">
                <div>
                  <span>Today's Progress</span>
                  <strong>{plan.completedTasks} / {plan.totalTasks} tasks completed</strong>
                </div>
                <div
                  className="ua-progress"
                  role="progressbar"
                  aria-valuemin={0}
                  aria-valuemax={100}
                  aria-valuenow={progress}
                  aria-label="Today's progress"
                >
                  <span style={{ width: `${progress}%` }}></span>
                </div>
              </div>

              {taskError && (
                <p className="ua-field-error plan-task-error" role="alert">
                  <FiAlertCircle aria-hidden="true" />
                  {taskError}
                </p>
              )}

              <ul className="plan-task-list">

                {plan.tasks.map((task) => {
                  const viaPractice = task.completionSource === "PRACTICE";
                  const saving = savingKey === task.id;

                  return (
                    <li
                      key={task.id}
                      className={`plan-task ${task.completed ? "completed" : "not-started"}`}
                    >

                      <button
                        type="button"
                        className="plan-task-check"
                        onClick={() => onToggle(task)}
                        disabled={Boolean(savingKey) || viaPractice}
                        aria-pressed={task.completed}
                        aria-label={
                          viaPractice
                            ? `${task.title} completed by today's practice`
                            : task.completed
                              ? `Mark ${task.title} as not completed`
                              : `Mark ${task.title} as completed`
                        }
                        title={viaPractice ? "Completed by today's practice" : undefined}
                      >
                        {saving
                          ? <FiLoader className="auth-spinner" />
                          : task.completed ? <FiCheckCircle /> : <FiCircle />}
                      </button>

                      <div className="plan-task-body">
                        <span className="plan-task-category">
                          {TYPE_LABELS[task.type] || task.type}
                          <span className={`plan-priority ${task.priority.toLowerCase()}`}>
                            {PRIORITY_LABELS[task.priority] || task.priority}
                          </span>
                        </span>
                        <strong>{task.title}</strong>
                        <p>{task.description}</p>
                        <span className="plan-task-meta">
                          <FiClock aria-hidden="true" />
                          {task.durationMinutes} min
                          {viaPractice && " · completed by practice"}
                        </span>
                      </div>

                      <div className="plan-task-actions">
                        <Link
                          to={task.route}
                          className="ua-button small"
                        >
                          {task.completed ? "Review" : "Open"}
                          <FiArrowRight aria-hidden="true" />
                        </Link>
                      </div>

                    </li>
                  );
                })}

              </ul>

              <p className="ua-footnote">
                Tasks tick automatically when you finish matching practice today. Progress is saved to your account.
              </p>
            </>
          )}

        </section>


        <div className="plan-side">

          {/* RECOMMENDED NEXT ACTION */}

          <section className="ua-card plan-next">

            <span className="ua-card-kicker">RECOMMENDED NEXT ACTION</span>

            {next ? (
              <>
                <h2>{next.title}</h2>
                <p>{next.description}</p>
                <Link
                  to={next.route}
                  className="ua-button primary"
                >
                  Start {next.title}
                  <FiArrowRight aria-hidden="true" />
                </Link>
              </>
            ) : (
              <>
                <h2>Today's plan is complete</h2>
                <p>Review your skill gap to see what to focus on tomorrow.</p>
                <Link
                  to="/career/skill-gap"
                  className="ua-button primary"
                >
                  View Skill Gap
                  <FiArrowRight aria-hidden="true" />
                </Link>
              </>
            )}

          </section>


          {/* PRIORITY SKILLS */}

          <section className="ua-card">

            <div className="ua-card-header">
              <div>
                <span className="ua-card-kicker">PRIORITY SKILLS</span>
                <h2>Focus areas</h2>
              </div>
              <Link
                to="/career/skill-gap"
                className="ua-card-link"
              >
                Skill Gap
              </Link>
            </div>

            {plan.prioritySkills.length ? (
              <ul className="plan-skill-list">
                {plan.prioritySkills.map((skill) => (
                  <li key={skill.name}>
                    <Link
                      to={skill.practiceRoute}
                      className={`plan-skill ${skill.score != null ? skill.status.toLowerCase() : "unassessed"}`}
                    >
                      {skill.score != null ? <FiAlertCircle aria-hidden="true" /> : <FiPlay aria-hidden="true" />}
                      <span>
                        <strong>{skill.name}</strong>
                        <small>
                          {skill.score != null
                            ? `${skill.score}% · ${skill.status.charAt(0)}${skill.status.slice(1).toLowerCase()}`
                            : skill.status === "SELF_REPORTED" ? "Self-reported · assess it" : "Not assessed yet"}
                        </small>
                      </span>
                      <FiArrowRight
                        className="plan-skill-arrow"
                        aria-hidden="true"
                      />
                    </Link>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="ua-muted">All assessed required skills are at Good or Strong.</p>
            )}

          </section>

        </div>

      </div>


      {/* WEEKLY PROGRESS */}

      <section className="ua-card">

        <div className="ua-card-header">
          <div>
            <span className="ua-card-kicker">WEEKLY PROGRESS</span>
            <h2>This week</h2>
          </div>
          <span className="ua-chip">
            {plan.weeklyProgress.filter((day) => day.practiceSessions > 0 || day.completedTasks > 0).length} active days
          </span>
        </div>

        <ol className="plan-week">
          {plan.weeklyProgress.map((day) => {
            const active = day.practiceSessions > 0 || day.completedTasks > 0;
            const isPast = !day.today && day.date < plan.date;

            let state = "upcoming";
            if (active) state = "done";
            else if (day.today) state = "today";
            else if (isPast) state = "missed";

            return (
              <li
                key={day.date}
                className={`plan-day ${state}${day.today ? " is-today" : ""}`}
                aria-current={day.today ? "date" : undefined}
              >
                <span className="plan-day-name">{day.label}</span>
                <span className="plan-day-date">{Number(day.date.slice(8, 10))}</span>
                <span className="plan-day-focus">
                  {day.practiceSessions} {day.practiceSessions === 1 ? "session" : "sessions"}
                </span>
                <span className="plan-day-state">
                  {day.completedTasks} {day.completedTasks === 1 ? "task" : "tasks"} ticked
                </span>
              </li>
            );
          })}
        </ol>

      </section>


      {/* ROADMAP */}

      {track && (
        <section className="ua-card">

          <div className="ua-card-header">
            <div>
              <span className="ua-card-kicker">ROADMAP</span>
              <h2>{track.title} topics</h2>
            </div>
            <Link
              to={`/career-tracks/${track.id}`}
              className="ua-card-link"
            >
              Full roadmap
            </Link>
          </div>

          <ol className="plan-roadmap">
            {track.roadmap.slice(0, 4).map((topic, index) => (
              <li key={topic.id}>
                <Link to={`/career-tracks/${track.id}/topic/${topic.id}`}>
                  <span className="plan-roadmap-number">{index + 1}</span>
                  <span className="plan-roadmap-text">
                    <strong>{topic.title}</strong>
                    <small>{topic.purpose}</small>
                  </span>
                  {index === 0 ? <FiBookOpen aria-hidden="true" /> : <FiMap aria-hidden="true" />}
                </Link>
              </li>
            ))}
          </ol>

        </section>
      )}

    </>
  );
}

export default MyPlan;
