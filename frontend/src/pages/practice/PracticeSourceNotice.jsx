import { FiCpu, FiInfo, FiLoader } from "react-icons/fi";

/** Labels where practice content came from: AI, demo fallback, or demo for signed-out users. */
export function PracticeSourceNotice({ source, notice }) {
  if (source === "ai") {
    return (
      <p className="practice-source-note ai">
        <FiCpu />
        AI-generated by CareerAI · review explanations critically
      </p>
    );
  }

  if (notice) {
    return (
      <p className="practice-inline-note practice-source-note fallback" role="status">
        <FiInfo />
        {notice}
      </p>
    );
  }

  return null;
}

export function PracticeLoading({ label = "Generating your practice set..." }) {
  return (
    <div className="practice-empty-state practice-loading-state" role="status">
      <FiLoader className="resume-spin" />
      <p>{label}</p>
    </div>
  );
}
