import api from "./api";

/* =====================================================
   PLAN SERVICE — today's plan is generated by the backend; only
   task completion (per user, per day) is stored.
   GET /plan/me
   PUT /plan/tasks/{taskKey}/complete | /incomplete  → returns the updated plan
===================================================== */

export async function getMyPlan() {
  const { data } = await api.get("/plan/me");
  return data;
}

export async function setPlanTaskCompleted(taskKey, completed) {
  const action = completed ? "complete" : "incomplete";
  const { data } = await api.put(`/plan/tasks/${encodeURIComponent(taskKey)}/${action}`);
  return data;
}
